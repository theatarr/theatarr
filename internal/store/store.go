// Package store is the SQLite database: one writer connection, a read-only reader pool, goose migrations and
// backups.
//
// # Connections
//
// SQLite allows one writer at a time. Rather than let several connections race for the lock and fail with
// SQLITE_BUSY, every write goes through one *sql.DB with exactly one connection, and its transactions start with
// BEGIN IMMEDIATE (the driver's _txlock=immediate), so a transaction takes the write lock up front instead of
// failing on its first write. Reads use a separate pool opened read-only; in WAL mode they never block the writer
// and the writer never blocks them.
//
// Pragmas on every connection: journal_mode=WAL (writer; it persists in the file), busy_timeout, foreign_keys=ON,
// synchronous=NORMAL. Readers also set query_only.
//
// # Timestamps
//
// Every timestamp column is INTEGER Unix milliseconds in UTC, named *_at (BIGINT in Postgres). They sort and compare
// as plain numbers, which the job queue's run_at and lease_until need, and they carry no time zone ambiguity. Use
// [Millis] and [FromMillis] to convert. Calendar dates with no time (an episode's air date) are TEXT 'YYYY-MM-DD'.
//
// # Portability
//
// The schema stays close to what Postgres accepts: plain types (INTEGER, TEXT, REAL), JSON in TEXT columns (jsonb in
// Postgres), booleans as INTEGER 0/1 with a CHECK, enums as TEXT with a CHECK, and unique rules over expressions as
// CREATE UNIQUE INDEX. Ids are INTEGER PRIMARY KEY (rowid); ids that clients see (titles, episodes, links,
// downloads) use AUTOINCREMENT so a deleted id is never handed out again. In Postgres both become
// BIGINT GENERATED BY DEFAULT AS IDENTITY.
package store

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"runtime"
	"time"

	"modernc.org/sqlite"
	sqlite3 "modernc.org/sqlite/lib"
)

// Options tune Open. The zero value is fine.
type Options struct {
	// BusyTimeout is SQLite's busy_timeout: how long a statement waits for a lock before SQLITE_BUSY.
	// Default 5s.
	BusyTimeout time.Duration
	// Readers is the size of the read-only pool. Default max(4, GOMAXPROCS).
	Readers int
	// MaxRetries is how often WriteTx retries a transaction that failed with SQLITE_BUSY. Default 5.
	MaxRetries int
	// RetryBackoff is the first wait between retries; it doubles each time. Default 50ms.
	RetryBackoff time.Duration
	// OnBusyRetry, if set, is called each time WriteTx retries (for metrics and tests).
	OnBusyRetry func()
	// ReadOnly opens an existing file through the read-only pool only (mode=ro, query_only): no file is created,
	// chmodded or switched to WAL, and the writer is that pool too, so any write fails.
	ReadOnly bool
}

func (o *Options) defaults() {
	if o.BusyTimeout <= 0 {
		o.BusyTimeout = 5 * time.Second
	}
	if o.Readers <= 0 {
		o.Readers = max(4, runtime.GOMAXPROCS(0))
	}
	if o.MaxRetries <= 0 {
		o.MaxRetries = 5
	}
	if o.RetryBackoff <= 0 {
		o.RetryBackoff = 50 * time.Millisecond
	}
}

// Store is an open database.
type Store struct {
	path   string
	opts   Options
	writer *sql.DB
	reader *sql.DB
}

// Open opens (creating if needed) the database file at path, refusing a schema newer than this binary knows.
// It does not migrate; call [Store.Migrate].
func Open(ctx context.Context, path string, opts Options) (*Store, error) {
	opts.defaults()
	if path == "" {
		return nil, errors.New("store: empty database path")
	}
	abs, err := filepath.Abs(path)
	if err != nil {
		return nil, fmt.Errorf("store: %w", err)
	}
	if opts.ReadOnly {
		return openReadOnly(ctx, abs, opts)
	}
	if err := os.MkdirAll(filepath.Dir(abs), 0o700); err != nil {
		return nil, fmt.Errorf("store: %w", err)
	}
	// The database holds plaintext provider and indexer keys: owner-only from its first byte. SQLite gives the -wal
	// and -shm files the database's mode; ownerOnly fixes ones an older version left behind.
	if err := ownerOnly(abs, true); err != nil {
		return nil, fmt.Errorf("store: %w", err)
	}

	busy := fmt.Sprintf("busy_timeout(%d)", opts.BusyTimeout.Milliseconds())
	w, err := sql.Open("sqlite", dsn(abs, url.Values{
		"_pragma": {busy, "journal_mode(WAL)", "foreign_keys(1)", "synchronous(NORMAL)"},
		"_txlock": {"immediate"},
	}))
	if err != nil {
		return nil, fmt.Errorf("store: open writer: %w", err)
	}
	w.SetMaxOpenConns(1)
	w.SetMaxIdleConns(1)
	w.SetConnMaxLifetime(0)
	w.SetConnMaxIdleTime(0)
	// Open the writer first: it creates the file and switches it to WAL, which read-only connections can't do.
	if err := w.PingContext(ctx); err != nil {
		w.Close()
		return nil, fmt.Errorf("store: open %s: %w", abs, err)
	}
	if err := checkSchema(ctx, w); err != nil {
		w.Close()
		return nil, fmt.Errorf("store: open %s: %w", abs, err)
	}

	for _, sfx := range []string{"-wal", "-shm"} {
		if err := ownerOnly(abs+sfx, false); err != nil {
			w.Close()
			return nil, fmt.Errorf("store: %w", err)
		}
	}

	r, err := openReaders(ctx, abs, opts)
	if err != nil {
		w.Close()
		return nil, err
	}
	return &Store{path: abs, opts: opts, writer: w, reader: r}, nil
}

// openReaders opens the read-only pool.
func openReaders(ctx context.Context, abs string, opts Options) (*sql.DB, error) {
	busy := fmt.Sprintf("busy_timeout(%d)", opts.BusyTimeout.Milliseconds())
	r, err := sql.Open("sqlite", dsn(abs, url.Values{
		"mode":    {"ro"},
		"_pragma": {busy, "foreign_keys(1)", "synchronous(NORMAL)", "query_only(1)"},
	}))
	if err != nil {
		return nil, fmt.Errorf("store: open readers: %w", err)
	}
	r.SetMaxOpenConns(opts.Readers)
	r.SetMaxIdleConns(opts.Readers)
	if err := r.PingContext(ctx); err != nil {
		r.Close()
		return nil, fmt.Errorf("store: open readers: %w", err)
	}
	return r, nil
}

// openReadOnly is Open with Options.ReadOnly: the existing file through the read-only pool, which serves as the
// writer too.
func openReadOnly(ctx context.Context, abs string, opts Options) (*Store, error) {
	if _, err := os.Stat(abs); err != nil {
		return nil, fmt.Errorf("store: %w", err)
	}
	r, err := openReaders(ctx, abs, opts)
	if err != nil {
		return nil, err
	}
	if err := checkSchema(ctx, r); err != nil {
		r.Close()
		return nil, fmt.Errorf("store: open %s: %w", abs, err)
	}
	return &Store{path: abs, opts: opts, writer: r, reader: r}, nil
}

// ReadOnly reports whether the store was opened with Options.ReadOnly.
func (s *Store) ReadOnly() bool { return s.opts.ReadOnly }

// ownerOnly makes path mode 0600, creating it empty first when create is set; a missing path is left alone otherwise.
func ownerOnly(path string, create bool) error {
	if create {
		f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0o600)
		if err != nil {
			return err
		}
		if err := f.Close(); err != nil {
			return err
		}
	}
	if err := os.Chmod(path, 0o600); err != nil && (create || !errors.Is(err, os.ErrNotExist)) {
		return err
	}
	return nil
}

func dsn(path string, q url.Values) string {
	u := url.URL{Scheme: "file", Path: path, RawQuery: q.Encode()}
	// url.URL renders "file:///abs/path"; SQLite accepts that form.
	return u.String()
}

// Path is the absolute path of the database file.
func (s *Store) Path() string { return s.path }

// Reader is the read-only pool. Use it for every query that writes nothing.
func (s *Store) Reader() *sql.DB { return s.reader }

// Writer is the single writer connection. Prefer [Store.WriteTx]; use Writer directly only for single statements
// that need no transaction.
func (s *Store) Writer() *sql.DB { return s.writer }

// Optimize runs PRAGMA optimize on the writer: ANALYZE for the tables whose statistics the query planner lacks or
// that changed much. 0x10000 makes it consider every table, since the reads run on the other (query-only) pool. A
// read-only store does nothing.
func (s *Store) Optimize(ctx context.Context) error {
	if s.opts.ReadOnly {
		return nil
	}
	_, err := s.writer.ExecContext(ctx, `PRAGMA optimize=0x10002`)
	return err
}

// Close closes both pools.
func (s *Store) Close() error {
	if s.writer == s.reader {
		return s.reader.Close()
	}
	return errors.Join(s.reader.Close(), s.writer.Close())
}

// Ping checks that both pools answer.
func (s *Store) Ping(ctx context.Context) error {
	if err := s.reader.PingContext(ctx); err != nil {
		return err
	}
	return s.writer.PingContext(ctx)
}

// WriteTx runs fn in a write transaction (BEGIN IMMEDIATE) and commits it, or rolls back if fn returns an error.
// If SQLite answers SQLITE_BUSY (another process holds the write lock past busy_timeout), the whole transaction is
// retried with exponential back-off, up to Options.MaxRetries times. fn may therefore run more than once: it must not
// have side effects outside the transaction.
func (s *Store) WriteTx(ctx context.Context, fn func(*sql.Tx) error) error {
	backoff := s.opts.RetryBackoff
	for attempt := 0; ; attempt++ {
		err := s.writeTxOnce(ctx, fn)
		if err == nil || !IsBusy(err) || attempt >= s.opts.MaxRetries {
			return err
		}
		if s.opts.OnBusyRetry != nil {
			s.opts.OnBusyRetry()
		}
		select {
		case <-ctx.Done():
			return errors.Join(err, ctx.Err())
		case <-time.After(backoff):
		}
		backoff *= 2
	}
}

func (s *Store) writeTxOnce(ctx context.Context, fn func(*sql.Tx) error) (err error) {
	tx, err := s.writer.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer func() {
		if p := recover(); p != nil {
			tx.Rollback()
			panic(p)
		}
		if err != nil {
			tx.Rollback()
		}
	}()
	if err = fn(tx); err != nil {
		return err
	}
	return tx.Commit()
}

// IsBusy reports whether err is SQLITE_BUSY (any extended code) or SQLITE_LOCKED.
func IsBusy(err error) bool {
	var se *sqlite.Error
	if !errors.As(err, &se) {
		return false
	}
	switch se.Code() & 0xff {
	case sqlite3.SQLITE_BUSY, sqlite3.SQLITE_LOCKED:
		return true
	}
	return false
}

// IsUniqueViolation reports whether err is a UNIQUE or PRIMARY KEY constraint failure.
func IsUniqueViolation(err error) bool {
	var se *sqlite.Error
	if !errors.As(err, &se) {
		return false
	}
	switch se.Code() {
	case sqlite3.SQLITE_CONSTRAINT_UNIQUE, sqlite3.SQLITE_CONSTRAINT_PRIMARYKEY:
		return true
	}
	return false
}

// Backup writes a consistent copy of the database to dest with VACUUM INTO, the nightly backup (docs/design/overview.md). It
// runs outside the writer connection, so writes carry on meanwhile. The copy is written next to dest and renamed into place,
// so dest is either the old file or a complete new one. An existing dest is replaced.
func (s *Store) Backup(ctx context.Context, dest string) error {
	abs, err := filepath.Abs(dest)
	if err != nil {
		return fmt.Errorf("store: backup: %w", err)
	}
	if abs == s.path {
		return errors.New("store: backup: destination is the live database")
	}
	if err := os.MkdirAll(filepath.Dir(abs), 0o700); err != nil {
		return fmt.Errorf("store: backup: %w", err)
	}
	tmp := abs + ".partial"
	if err := os.Remove(tmp); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("store: backup: %w", err)
	}
	// A backup holds the same plaintext keys: VACUUM INTO fills an empty owner-only file, so it is never readable by
	// others, even while it is written.
	if err := ownerOnly(tmp, true); err != nil {
		return fmt.Errorf("store: backup: %w", err)
	}
	// A read-only connection can't run VACUUM INTO (it writes the new file through the source connection), so the
	// backup gets a short-lived connection of its own. It only reads the source, inside one WAL read transaction.
	db, err := sql.Open("sqlite", dsn(s.path, url.Values{
		"_pragma": {fmt.Sprintf("busy_timeout(%d)", s.opts.BusyTimeout.Milliseconds())},
	}))
	if err != nil {
		return fmt.Errorf("store: backup: %w", err)
	}
	defer db.Close()
	db.SetMaxOpenConns(1)
	if _, err := db.ExecContext(ctx, "VACUUM INTO ?", tmp); err != nil {
		os.Remove(tmp)
		return fmt.Errorf("store: backup: %w", err)
	}
	if err := os.Rename(tmp, abs); err != nil {
		os.Remove(tmp)
		return fmt.Errorf("store: backup: %w", err)
	}
	return nil
}

// Millis converts t to the stored timestamp form: Unix milliseconds, UTC.
func Millis(t time.Time) int64 { return t.UnixMilli() }

// FromMillis converts a stored timestamp back to a UTC time.
func FromMillis(ms int64) time.Time { return time.UnixMilli(ms).UTC() }

// NullMillis converts a nullable stored timestamp; NULL gives the zero time.
func NullMillis(n sql.NullInt64) time.Time {
	if !n.Valid {
		return time.Time{}
	}
	return FromMillis(n.Int64)
}
